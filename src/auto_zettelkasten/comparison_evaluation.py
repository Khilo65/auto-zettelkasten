"""Evidence-budget evaluation for opt-in retrieval experiments.

No model judgments are inferred here. References are supplied by reviewers and
unresolved judgments remain unresolved. This module has no provider or file IO.
"""
from __future__ import annotations

from collections.abc import Mapping, Sequence
import hashlib
import json
import math
import re
from typing import Any


def _normalized(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def evaluate_evidence(packet: Mapping[str, Any], reference: Mapping[str, Any]) -> dict[str, Any]:
    """Score quoted evidence, distinguishing a found source from a found passage.

    A unit may have several acceptable source/quote alternatives. Merely finding
    an expected endpoint never counts as retrieving its supporting passage.
    """
    notes = packet.get("notes", [])
    units = reference.get("evidence_units", [])
    if not isinstance(notes, (list, tuple)) or len(notes) > 1000:
        raise ValueError("notes must be a bounded sequence")
    if not isinstance(units, (list, tuple)) or len(units) > 1000:
        raise ValueError("evidence_units must be a bounded sequence")
    sources: dict[str, list[str]] = {}
    for row in notes:
        if not isinstance(row, Mapping) or not isinstance(row.get("source_id"), str) or not row["source_id"]:
            raise ValueError("each note requires a source identity")
        # Claims generated by a framework are deliberately not source excerpts.
        text = row.get("excerpt", row.get("text"))
        if text is None:
            # The as-deployed route exposes these compact fields, not a full
            # note excerpt. Credit only text it actually returned.
            fields = [row.get(name, "") for name in ("thesis", "method")]
            if any(not isinstance(field, str) for field in fields):
                raise ValueError("legacy note evidence must be text")
            text = "\n".join(fields)
        if not isinstance(text, str) or len(text) > 1_000_000:
            raise ValueError("note excerpt must be bounded text")
        if row.get("grounding_status") in {"ungrounded", "unmapped", "invalid"}:
            continue
        sources.setdefault(row["source_id"], []).append(_normalized(text))
    seen: set[str] = set()
    outcomes = []
    for unit in units:
        if not isinstance(unit, Mapping):
            raise ValueError("evidence unit must be an object")
        uid, importance = unit.get("unit_id"), unit.get("importance")
        if not isinstance(uid, str) or not uid or uid in seen:
            raise ValueError("evidence units require unique identities")
        seen.add(uid)
        if importance not in {"essential", "helpful"}:
            raise ValueError("importance must be essential or helpful")
        alternatives = unit.get("alternatives", [])
        if not isinstance(alternatives, (list, tuple)) or not alternatives or len(alternatives) > 100:
            raise ValueError("each unit requires bounded evidence alternatives")
        source_found = False
        matches = []
        for alternative in alternatives:
            if not isinstance(alternative, Mapping):
                raise ValueError("evidence alternative must be an object")
            sid, quote = alternative.get("source_id"), alternative.get("quote")
            if not isinstance(sid, str) or not sid or not isinstance(quote, str) or not _normalized(quote):
                raise ValueError("alternatives require source identity and nonempty quote")
            source_found |= sid in sources
            if any(_normalized(quote) in excerpt for excerpt in sources.get(sid, [])):
                matches.append(sid)
        outcomes.append({"unit_id": uid, "importance": importance, "source_found": source_found,
                         "passage_found": bool(matches), "matched_source_ids": sorted(set(matches))})
    judgments = reference.get("source_judgments", [])
    if not isinstance(judgments, (list, tuple)) or len(judgments) > 10000:
        raise ValueError("source judgments must be bounded")
    reviewed: dict[str, str] = {}
    for row in judgments:
        if not isinstance(row, Mapping) or not isinstance(row.get("source_id"), str):
            raise ValueError("source judgment requires identity")
        label = row.get("label")
        if label not in {"essential", "helpful", "redundant", "misleading", "uncertain", "unresolved"}:
            raise ValueError("unknown review label")
        sid = row["source_id"]
        if sid in reviewed and reviewed[sid] != label:
            reviewed[sid] = "unresolved"
        else:
            reviewed[sid] = label
    totals = {}
    for importance in ("essential", "helpful"):
        selected = [row for row in outcomes if row["importance"] == importance]
        totals[importance] = {"available_units": len(selected),
                              "sources_found": sum(row["source_found"] for row in selected),
                              "passages_found": sum(row["passage_found"] for row in selected)}
    reference_sha256 = hashlib.sha256(json.dumps(reference, ensure_ascii=False, sort_keys=True,
                                                 separators=(",", ":"), allow_nan=False).encode()).hexdigest()
    return {"task_id": reference.get("task_id"), "variant": packet.get("variant"),
            "reference_sha256": reference_sha256,
            "units": outcomes, "totals": totals, "unique_sources": len(sources),
            "returned_review_labels": {label: sum(reviewed.get(sid) == label for sid in sources)
                                       for label in ("essential", "helpful", "redundant", "misleading", "uncertain", "unresolved")},
            "unreviewed_sources": sorted(sid for sid in sources if sid not in reviewed),
            "interpretation": "quote recovery only; no automatic factual or answer-quality judgment"}


def compare_paired_results(baseline: Sequence[Mapping[str, Any]], challenger: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    """Describe paired outcomes without declaring an automatic rollout winner."""
    def keyed(rows):
        result = {}
        for row in rows:
            task = row.get("task_id")
            if not isinstance(task, str) or not task or task in result:
                raise ValueError("paired results require unique task identities")
            result[task] = row
        return result
    left, right = keyed(baseline), keyed(challenger)
    if not left or left.keys() != right.keys():
        raise ValueError("paired results must contain the same nonempty task set")
    rows = []
    for task in sorted(left):
        a, b = left[task], right[task]
        if not a.get("reference_sha256") or a.get("reference_sha256") != b.get("reference_sha256"):
            raise ValueError("paired results must use the same frozen reference")
        if a.get("units") is None or b.get("units") is None:
            raise ValueError("paired results require evaluated evidence units")
        if [(r["unit_id"], r["importance"]) for r in a["units"]] != [(r["unit_id"], r["importance"]) for r in b["units"]]:
            raise ValueError("paired results must share the same reference units")
        rows.append({"task_id": task, "essential_passage_delta": b["totals"]["essential"]["passages_found"] - a["totals"]["essential"]["passages_found"],
                     "helpful_passage_delta": b["totals"]["helpful"]["passages_found"] - a["totals"]["helpful"]["passages_found"],
                     "reviewed_misleading_delta": b["returned_review_labels"]["misleading"] - a["returned_review_labels"]["misleading"]})
    return {"paired_tasks": len(rows), "tasks": rows,
            "essential_improved_tasks": sum(r["essential_passage_delta"] > 0 for r in rows),
            "essential_regressed_tasks": sum(r["essential_passage_delta"] < 0 for r in rows),
            "rollout": "not_authorized", "conclusion": "requires paired evidence review; small differences may be inconclusive"}


def resource_record(*, elapsed_seconds: float, peak_rss_bytes: int, disk_delta_bytes: int,
                    provider_calls: int, actual_cost_usd: str | None) -> dict[str, Any]:
    if isinstance(elapsed_seconds, bool) or not isinstance(elapsed_seconds, (int, float)) or not math.isfinite(elapsed_seconds) or elapsed_seconds < 0:
        raise ValueError("elapsed time must be finite and nonnegative")
    for name, value in (("peak_rss_bytes", peak_rss_bytes), ("provider_calls", provider_calls)):
        if type(value) is not int or value < 0:
            raise ValueError(f"{name} must be a nonnegative integer")
    if type(disk_delta_bytes) is not int:
        raise ValueError("disk delta must be an integer")
    from decimal import Decimal, InvalidOperation
    if actual_cost_usd is not None:
        if not isinstance(actual_cost_usd, str):
            raise ValueError("actual cost must be a decimal string")
        try:
            amount = Decimal(actual_cost_usd)
        except (InvalidOperation, TypeError):
            raise ValueError("actual cost must be a decimal string") from None
        if not amount.is_finite() or amount < 0:
            raise ValueError("actual cost must be finite and nonnegative")
    return {"elapsed_seconds": elapsed_seconds, "peak_rss_bytes": peak_rss_bytes,
            "disk_delta_bytes": disk_delta_bytes, "provider_calls": provider_calls,
            "actual_cost_usd": actual_cost_usd,
            "time_role": "resource_diagnostic_only; no research stopwatch"}
